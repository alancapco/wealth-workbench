"""Consent management service: request, check, withdraw with policy enforcement."""
from datetime import datetime, UTC
from typing import Optional
from uuid import UUID

from sqlalchemy import select
from sqlalchemy.ext.asyncio import AsyncSession

from app.models.capture import ConsentRecord
from app.models.workflow import Meeting


class ConsentService:
    """Manage meeting capture consent with fail-closed policy enforcement."""

    def __init__(self, session: AsyncSession):
        self.session = session

    async def record_consent(
        self,
        tenant_id: str,
        client_id: UUID,
        meeting_id: UUID,
        policy_configuration_id: UUID,
        jurisdiction: str,
        platform: str,
        language: str,
        method: str,
        participant_refs: list[str],
        decision: str,  # ACCEPTED or DECLINED
        actor: str,
    ) -> ConsentRecord:
        """Record consent decision (ACCEPTED/DECLINED) with policy reference.
        
        Fail-closed: missing policy blocks consent recording upstream.
        Calendar acceptance is NOT consent.
        """
        if decision not in ("ACCEPTED", "DECLINED"):
            raise ValueError(f"Invalid consent decision: {decision}")

        consent = ConsentRecord(
            id=UUID,  # Generated by caller
            tenant_id=tenant_id,
            client_id=client_id,
            meeting_id=meeting_id,
            policy_configuration_id=policy_configuration_id,
            jurisdiction=jurisdiction,
            platform=platform,
            language=language,
            method=method,
            participant_refs=participant_refs,
            state=decision,
            actor=actor,
            recorded_at=datetime.now(UTC),
            row_version=1,
        )
        
        self.session.add(consent)
        await self.session.flush()
        return consent

    async def get_current_consent(
        self,
        tenant_id: str,
        client_id: UUID,
        meeting_id: UUID,
    ) -> Optional[ConsentRecord]:
        """Get the most recent consent for a meeting."""
        stmt = (
            select(ConsentRecord)
            .where(
                ConsentRecord.tenant_id == tenant_id,
                ConsentRecord.client_id == client_id,
                ConsentRecord.meeting_id == meeting_id,
            )
            .order_by(ConsentRecord.recorded_at.desc())
            .limit(1)
        )
        result = await self.session.execute(stmt)
        return result.scalar_one_or_none()

    async def check_consent_valid(
        self,
        tenant_id: str,
        client_id: UUID,
        meeting_id: UUID,
    ) -> bool:
        """Check if current consent is ACCEPTED and not WITHDRAWN.
        
        Returns False if declined, withdrawn, or no consent exists (fail-closed).
        """
        consent = await self.get_current_consent(tenant_id, client_id, meeting_id)
        if not consent:
            return False
        return consent.state == "ACCEPTED"

    async def withdraw_consent(
        self,
        tenant_id: str,
        client_id: UUID,
        consent_id: UUID,
        actor: str,
    ) -> ConsentRecord:
        """Withdraw consent and invalidate dependent capture.
        
        Caller must:
        1. Stop active capture sessions
        2. Invalidate dependent artifact refs
        """
        stmt = select(ConsentRecord).where(
            ConsentRecord.tenant_id == tenant_id,
            ConsentRecord.client_id == client_id,
            ConsentRecord.id == consent_id,
        )
        result = await self.session.execute(stmt)
        consent = result.scalar_one_or_none()
        
        if not consent:
            raise ValueError(f"Consent {consent_id} not found")
        
        if consent.state == "WITHDRAWN":
            return consent  # Idempotent
        
        consent.state = "WITHDRAWN"
        consent.withdrawn_at = datetime.now(UTC)
        consent.row_version += 1
        
        await self.session.flush()
        return consent
